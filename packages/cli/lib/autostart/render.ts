import { createHash } from "node:crypto"
import * as path from "node:path"

import { ServiceName } from "@/services/definitions"

/** Everything needed to describe one background service to the OS. */
export type UnitSpec = {
  service: ServiceName
  /** Human description, shown in the unit. */
  description: string
  /** Absolute path of the node binary; no PATH lookup at login. */
  execPath: string
  /** Absolute path of the service's script. */
  script: string
  args: string[]
  env: Record<string, string>
  logFile: string
  /** Service whose unit this one should start after (systemd ordering). */
  after?: { service: ServiceName }
}

/**
 * Names the OS uses for our units. They depend on the velo data directory: the usual `~/.velo`
 * gets the plain names, any other directory (a `VELO_HOME` sandbox) gets a short hash in the
 * name, so setting up autostart from a sandbox can never replace or remove the real one.
 */
export const unitNames = (home: string, defaultHome: string, service: ServiceName) => {
  const isDefault = path.resolve(home) === path.resolve(defaultHome)
  const tag = isDefault
    ? ""
    : createHash("sha1").update(path.resolve(home)).digest("hex").slice(0, 8)
  return {
    isDefault,
    launchdLabel: isDefault
      ? `dev.starktech.velo.${service}`
      : `dev.starktech.velo.${tag}.${service}`,
    systemdUnit: isDefault ? `velo-${service}.service` : `velo-${tag}-${service}.service`,
  }
}

const xml = (value: string) =>
  value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;")

const shellQuote = (value: string): string => `'${value.replace(/'/g, `'\\''`)}'`

/**
 * The program macOS runs for the login item. macOS names a login item after the *signer* of the
 * program launchd executes, and the node binary is signed by the Node.js Foundation, so running
 * node directly shows up in System Settings as "Node.js Foundation". An unsigned script is shown
 * under its own file name instead ("velo-api"); it then replaces itself with node.
 */
export const renderLauncherScript = (spec: UnitSpec): string =>
  `#!/bin/sh
# Generated by \`velo service install\`; edit nothing here, it is rewritten on reinstall.
# macOS lists a login item under the name of the program it runs, so this exists to be named
# "velo-${spec.service}" rather than "Node.js Foundation". It hands over to node immediately.
exec ${[spec.execPath, spec.script, ...spec.args].map(shellQuote).join(" ")}
`

/**
 * A launchd agent that starts at login and restarts only after a crash (a clean exit stays
 * stopped). With `launcher`, the agent runs that script (see renderLauncherScript) instead of
 * node directly.
 */
export const renderLaunchdPlist = (label: string, spec: UnitSpec, launcher?: string): string => {
  const strings = (items: string[]) => items.map((i) => `    <string>${xml(i)}</string>`).join("\n")
  const env = Object.entries(spec.env)
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>${xml(label)}</string>
  <key>ProgramArguments</key>
  <array>
${strings(launcher ? [launcher] : [spec.execPath, spec.script, ...spec.args])}
  </array>
  <key>RunAtLoad</key>
  <true/>
  <key>KeepAlive</key>
  <dict>
    <key>SuccessfulExit</key>
    <false/>
  </dict>
  <key>ProcessType</key>
  <string>Background</string>
  <key>StandardOutPath</key>
  <string>${xml(spec.logFile)}</string>
  <key>StandardErrorPath</key>
  <string>${xml(spec.logFile)}</string>${
    env.length
      ? `
  <key>EnvironmentVariables</key>
  <dict>
${env.map(([k, v]) => `    <key>${xml(k)}</key>\n    <string>${xml(v)}</string>`).join("\n")}
  </dict>`
      : ""
  }
</dict>
</plist>
`
}

/** systemd treats `%` and `$` specially and splits on spaces, so quote each argument. */
export const systemdQuote = (arg: string): string =>
  /^[A-Za-z0-9_@%+=:,./-]+$/.test(arg) && !arg.includes("%")
    ? arg
    : `"${arg.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/%/g, "%%").replace(/\$/g, "$$$$")}"`

/** A systemd user unit; wanted by default.target so it starts at login. */
export const renderSystemdUnit = (spec: UnitSpec, afterUnit?: string): string => {
  const exec = [spec.execPath, spec.script, ...spec.args].map(systemdQuote).join(" ")
  const env = Object.entries(spec.env).map(([k, v]) => `Environment=${systemdQuote(`${k}=${v}`)}`)
  return `[Unit]
Description=${spec.description}${
    afterUnit
      ? `
After=${afterUnit}
Wants=${afterUnit}`
      : ""
  }

[Service]
ExecStart=${exec}
Restart=on-failure
RestartSec=3${env.length ? `\n${env.join("\n")}` : ""}
StandardOutput=append:${spec.logFile}
StandardError=append:${spec.logFile}

[Install]
WantedBy=default.target
`
}
